function buildPagination() {
    const container = document.getElementById("pagination-container");
    let html = "";
    
    const sortedKeys = Object.keys(novelData.chapters).sort((a,b) => parseInt(a) - parseInt(b));
    
    sortedKeys.forEach(id => {
        const ch = novelData.chapters[id];
        html += `
            <a href="#/chapter/${ch.id}" class="page-link" id="pag-link-${ch.id}">
                ตอนที่ ${ch.id}
            </a>
        `;
    });
    
    html += `
        <a href="#/world" class="page-link" id="pag-link-world">
            <i class="fa-solid fa-globe"></i> ข้อมูลสร้างโลก
        </a>
    `;
    
    container.innerHTML = html;
}

function updateActivePagination(hash) {
    const links = document.querySelectorAll(".pagination-links .page-link");
    links.forEach(lnk => lnk.classList.remove("active"));
    
    let activeId = "";
    if (hash.startsWith('#/chapter/')) {
        activeId = `pag-link-${hash.replace('#/chapter/', '')}`;
    } else if (hash === '#/world') {
        activeId = "pag-link-world";
    }
    
    const activeLink = document.getElementById(activeId);
    if (activeLink) activeLink.classList.add("active");
}

