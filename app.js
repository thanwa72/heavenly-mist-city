// FORMAT NOVEL CONTENT WITH BEAUTIFUL TAGS
function formatNovelContent(text) {
    let formatted = text.trim();
    
    // Handle BGM
    formatted = formatted.replace(/\[ดนตรีประกอบ \/ BGM:\s*([^\]]+)\]/g, (match, p1) => {
        return `<div class="audio-note audio-bgm"><i class="fa-solid fa-music"></i> <strong>[ดนตรีประกอบ]:</strong> ${p1}</div>`;
    });
    
    // Handle SFX
    formatted = formatted.replace(/\[เสียงเอฟเฟกต์ \/ SFX:\s*([^\]]+)\]/g, (match, p1) => {
        return `<div class="audio-note audio-sfx"><i class="fa-solid fa-volume-high"></i> <strong>[เสียงเอฟเฟกต์]:</strong> ${p1}</div>`;
    });
    
    let paragraphs = formatted.split('\n\n');
    let parsedHTML = paragraphs.map(p => {
        p = p.trim();
        if (!p) return '';
        
        if (p.startsWith('[ระบบ') || p.startsWith('[คำเตือน')) {
            return `<div style="background: rgba(212,175,55,0.08); padding: 15px; border-left: 4px solid var(--color-gold); border-radius: 4px; margin: 15px 0; font-family: var(--font-heading); color: #fff;">${p}</div>`;
        }
        
        if (p.startsWith('"') && p.endsWith('"')) {
            return `<div class="dialogue-block"><span class="char-speech">${p}</span></div>`;
        }
        
        const speakerMatch = p.match(/^([^:\n]+):\s*"([^"]+)"/);
        if (speakerMatch) {
            return `
                <div class="dialogue-block">
                    <div class="char-speaker">${speakerMatch[1]}</div>
                    <div class="char-speech">"${speakerMatch[2]}"</div>
                </div>
            `;
        }
        
        return `<p>${p}</p>`;
    }).join('');
    
    return parsedHTML;
}

